#!/usr/bin/env node
/**
 * Builds a single self-contained executable containing the backend, all of its
 * dependencies, and the built frontend.
 *
 * Steps:
 *   1. npm ci + vite build in frontend/
 *   2. embed frontend/dist into backend/frontend-assets.generated.js
 *   3. esbuild-bundle backend/server.js into one CommonJS file
 *   4. Node SEA: build a blob and inject it into a copy of the node binary
 *
 * `sharp` is deliberately excluded: it is the only native dependency in the
 * tree, and baileys imports it with a .catch() fallback to jimp (pure JS), so
 * dropping it keeps the bundle portable at the cost of slower thumbnailing.
 *
 * Node SEA cannot cross-compile - run this on the OS you are targeting.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const build = path.join(root, 'build');
const isWindows = process.platform === 'win32';
const exeName = 'whatsapp-slack-bridge' + (isWindows ? '.exe' : '');

// `npm ci` wipes node_modules, which fails locally if a dev server holds file
// locks. CI always starts clean, so use the reproducible install only there.
const installCmd = process.env.CI ? 'ci' : 'install';

// npm/npx need a shell on Windows (.cmd shims). Direct executables must NOT
// use one: process.execPath contains a space, which the shell would split.
const run = (cmd, args, cwd, useShell) => {
  console.log(`\n> ${cmd} ${args.join(' ')}`);
  execFileSync(cmd, args, { cwd: cwd || root, stdio: 'inherit', shell: useShell === undefined ? isWindows : useShell });
};

const MIME = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8', '.json': 'application/json',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg',
  '.ico': 'image/x-icon', '.woff': 'font/woff', '.woff2': 'font/woff2',
  '.map': 'application/json', '.txt': 'text/plain; charset=utf-8',
};

function embedFrontend() {
  const dist = path.join(root, 'frontend', 'dist');
  if (!fs.existsSync(dist)) throw new Error('frontend/dist missing - the frontend build did not run');

  const assets = {};
  (function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) { walk(full); continue; }
      const rel = path.relative(dist, full).split(path.sep).join('/');
      assets[rel] = {
        type: MIME[path.extname(entry.name).toLowerCase()] || 'application/octet-stream',
        b64: fs.readFileSync(full).toString('base64'),
      };
    }
  })(dist);

  const out = path.join(root, 'backend', 'frontend-assets.generated.js');
  fs.writeFileSync(out, '// Generated by scripts/build-standalone.mjs - do not edit.\nmodule.exports = ' + JSON.stringify(assets) + ';\n');

  const kb = (fs.statSync(out).size / 1024).toFixed(0);
  console.log(`\nEmbedded ${Object.keys(assets).length} frontend file(s) (${kb} KB)`);
}

// 1. frontend
run('npm', [installCmd, '--no-audit', '--no-fund'], path.join(root, 'frontend'));
run('npm', ['run', 'build'], path.join(root, 'frontend'));

// 2. embed
embedFrontend();

// 3. backend bundle
run('npm', [installCmd, '--no-audit', '--no-fund'], path.join(root, 'backend'));
fs.mkdirSync(build, { recursive: true });
run('npx', ['--yes', 'esbuild@0.25.0', 'server.js',
  '--bundle', '--platform=node', '--target=node20', '--format=cjs',
  '--external:sharp',
  `--define:__BRIDGE_VERSION__=${JSON.stringify(JSON.stringify(process.env.BRIDGE_VERSION || 'dev'))}`,
  `--outfile=${path.join(build, 'bridge.cjs')}`], path.join(root, 'backend'));

// 4. Node SEA
const seaConfig = path.join(build, 'sea-config.json');
fs.writeFileSync(seaConfig, JSON.stringify({
  main: path.join(build, 'bridge.cjs'),
  output: path.join(build, 'sea-prep.blob'),
  disableExperimentalSEAWarning: true,
}, null, 2));

run(process.execPath, ['--experimental-sea-config', seaConfig], root, false);

const exePath = path.join(build, exeName);
fs.copyFileSync(process.execPath, exePath);

const postjectArgs = [
  '--yes', 'postject@1.0.0-alpha.6', exePath, 'NODE_SEA_BLOB',
  path.join(build, 'sea-prep.blob'),
  '--sentinel-fuse', 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2',
];
run('npx', postjectArgs);

const mb = (fs.statSync(exePath).size / 1024 / 1024).toFixed(1);
console.log(`\nBuilt ${exePath} (${mb} MB)`);
